#!/usr/bin/env python3
"""Generate the panel API reference from the panel SDK sources (ADR-052 Addendum 1).

The panel contract is not Python, so the Python reference generator
(``build_reference.py``) cannot see it. This module reads the contract from the
files that implement it and renders three self-contained Markdown pages into
the packaged API reference:

* ``panels-sdk.md`` -- ``window.scistudio`` from JSDoc blocks in
  ``sdk/<major>/scistudio-panel.js``, the per-context operations from
  ``PanelContext.provides``, the read operations from
  ``scistudio.panels.reads.READ_OPERATIONS``, and the pinned libraries from
  ``panels/lib/index.json``.
* ``panels-renderers.md`` -- the stylesheets and the components exported by
  ``panel-ui.js`` and re-exported by ``renderers.js``, from their JSDoc blocks;
  prop defaults are read from the component signatures.
* ``panel-descriptor.md`` -- the ``panel.json`` schema from
  ``scistudio.panels.descriptor.DESCRIPTOR_FIELDS`` and the ``panel.sample.json``
  shape from the SDK's ``@sample`` block.

JSDoc conventions (only ``/** ... */`` blocks are read):

* Tags are one line each; every non-tag line is description.
* ``@overview`` marks a file's overview block.
* An exported component's block sits directly above ``export function Name(``
  and documents its props as ``@param {type} [props.name] description``
  (brackets mark an optional prop). Defaults come from the signature.
* An SDK member's block carries ``@member name`` and optionally ``@group``,
  ``@context``, ``@type``, ``@param``, and ``@returns``.
* The SDK's ``@errors`` block lists ``@error code description``; its ``@sample``
  block lists ``@property {type} [name] description``.

The generator refuses to render a contract that disagrees with its code: an
undocumented export or SDK member, a documented prop the component does not
take, an SDK error code without a description, or a sample key the SDK does
not read all raise :class:`PanelReferenceError`. The committed pages are
compared with a fresh render by ``tests/docs/test_panel_reference.py``.

Run (never ``pip install -e .``)::

    PYTHONPATH=$PWD/src python scripts/docs/build_panel_reference.py
"""

