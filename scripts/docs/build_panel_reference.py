class PanelReferenceError(ValueError):
    """The panel sources and their documentation disagree."""


# --------------------------------------------------------------------------
# JSDoc parsing
# --------------------------------------------------------------------------

_BLOCK = re.compile(r"/\*\*(.*?)\*/", re.S)
_TAG = re.compile(r"@(\w+)\s*(.*)")


@dataclass
class Param:
    name: str
    type: str
    optional: bool
    description: str


@dataclass
class DocBlock:
    description: str
    tags: dict[str, list[str]]
    end: int
    params: list[Param] = field(default_factory=list)

    def first(self, tag: str) -> str | None:
        values = self.tags.get(tag)
        return values[0] if values else None


def _block_lines(raw: str) -> list[str]:
    lines = []
    for line in raw.split("\n"):
        stripped = line.strip()
        if stripped.startswith("*"):
            stripped = stripped[1:]
            if stripped.startswith(" "):
                stripped = stripped[1:]
        lines.append(stripped.rstrip())
    return lines


def _split_type(text: str) -> tuple[str, str] | None:
    """Split ``{type} rest`` where the type may itself contain braces."""
    text = text.strip()
    if not text.startswith("{"):
        return None
    depth = 0
    for index, char in enumerate(text):
        depth += {"{": 1, "}": -1}.get(char, 0)
        if depth == 0:
            return text[1:index].strip(), text[index + 1 :].strip()
    return None


def _param(text: str, *, where: str) -> Param:
    split = _split_type(text)
    match = re.fullmatch(r"(?P<name>\[[^\]]+\]|\S+)\s*(?P<desc>.*)", split[1]) if split else None
    if split is None or match is None:
        raise PanelReferenceError(f"{where}: malformed tag {text!r}; expected '{{type}} name description'")
    name = match["name"]
    optional = name.startswith("[")
    return Param(name.strip("[]"), split[0], optional, match["desc"].strip())


def parse_blocks(source: str, *, where: str) -> list[DocBlock]:
    """Every ``/** ... */`` block in ``source``, split into description and tags."""
    blocks: list[DocBlock] = []
    for match in _BLOCK.finditer(source):
        description: list[str] = []
        tags: dict[str, list[str]] = {}
        in_fence = False
        for line in _block_lines(match.group(1)):
            if line.startswith("```"):
                in_fence = not in_fence
            tag = None if in_fence else _TAG.match(line)
            if tag:
                tags.setdefault(tag.group(1), []).append(tag.group(2).strip())
            else:
                description.append(line)
        text = "\n".join(description).strip("\n")
        block = DocBlock(re.sub(r"\n{3,}", "\n\n", text), tags, match.end())
        block.params = [_param(p, where=where) for p in tags.get("param", []) + tags.get("property", [])]
        blocks.append(block)
    return blocks


def _matching(source: str, start: int, open_char: str, close_char: str) -> int:
    """Index just past the bracket that closes the one at ``start``."""
    depth = 0
    quote: str | None = None
    index = start
    while index < len(source):
        char = source[index]
        if quote:
            if char == "\\":
                index += 1
            elif char == quote:
                quote = None
        elif source.startswith("//", index):
            index = source.find("\n", index)
            if index < 0:
                break
        elif source.startswith("/*", index):
            index = source.find("*/", index) + 1
            if index <= 0:
                break
        elif char in "\"'`":
            quote = char
        elif char == open_char:
            depth += 1
        elif char == close_char:
            depth -= 1
            if depth == 0:
                return index + 1
        index += 1
    raise PanelReferenceError(f"unbalanced {open_char}{close_char} at offset {start}")


def _split_top_level(text: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    quote: str | None = None
    current: list[str] = []
    for index, char in enumerate(text):
        if quote:
            current.append(char)
            if char == quote and text[index - 1] != "\\":
                quote = None
            continue
        if char in "\"'`":
            quote = char
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append("".join(current))
            current = []
            continue
        current.append(char)
    parts.append("".join(current))
    return [part.strip() for part in parts if part.strip()]


@dataclass
class Signature:
    """A component's destructured props: name -> default source (``None`` when none)."""

    props: dict[str, str | None] | None
    has_rest: bool


def parse_signature(parameters: str) -> Signature:
    """Read the props a component destructures, and their defaults."""
    text = parameters.strip()
    if not text.startswith("{"):
        return Signature(None, False)
    props: dict[str, str | None] = {}
    has_rest = False
    for part in _split_top_level(text[1 : _matching(text, 0, "{", "}") - 1]):
        if part.startswith("..."):
            has_rest = True
            continue
        name, _, default = part.partition("=")
        key = name.split(":")[0].strip()
        props[key] = default.strip() or None
    return Signature(props, has_rest)


@dataclass
class Component:
    name: str
    module: str
    doc: DocBlock | None
    signature: Signature


def _exported_components(path: Path) -> dict[str, Component]:
    source = path.read_text(encoding="utf-8")
    blocks = parse_blocks(source, where=path.name)
    components: dict[str, Component] = {}
    for match in re.finditer(r"^export function (\w+)\s*\(", source, re.M):
        name = match.group(1)
        doc = next((b for b in blocks if b.end <= match.start() and not source[b.end : match.start()].strip()), None)
        open_paren = match.end() - 1
        parameters = source[open_paren + 1 : _matching(source, open_paren, "(", ")") - 1]
        components[name] = Component(name, path.name, doc, parse_signature(parameters))
    return components


def _check_component(component: Component) -> None:
    where = f"{component.module}: {component.name}"
    if component.doc is None or not component.doc.description:
        raise PanelReferenceError(f"{where} is exported without a JSDoc description")
    documented = []
    for param in component.doc.params:
        if not param.name.startswith("props."):
            raise PanelReferenceError(f"{where}: document props as 'props.<name>', got {param.name!r}")
        documented.append(param.name[len("props.") :])
    props = component.signature.props
    if props is None:
        return
    missing = sorted(set(props) - set(documented))
    extra = sorted(set(documented) - set(props))
    if missing or extra:
        raise PanelReferenceError(f"{where}: props undocumented {missing}, documented but not taken {extra}")


def _overview(path: Path) -> str:
    blocks = [b for b in parse_blocks(path.read_text(encoding="utf-8"), where=path.name) if "overview" in b.tags]
    if len(blocks) != 1:
        raise PanelReferenceError(f"{path.name}: expected exactly one @overview block, found {len(blocks)}")
    return blocks[0].description


def _re_exports(path: Path) -> list[tuple[str, str]]:
    source = path.read_text(encoding="utf-8")
    return re.findall(r'^export \{\s*(\w+)\s*\} from "\./([\w.-]+)";', source, re.M)


# --------------------------------------------------------------------------
# Rendering helpers
# --------------------------------------------------------------------------


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _stamp() -> str:
    return (
        f"> **Stability:** `{STABILITY}` · **Panel API version:** `{PANEL_API_VERSION}` · "
        f"**SDK path:** `sdk/{PANEL_API_MAJOR}/`\n"
    )


def _props_table(component: Component) -> list[str]:
    assert component.doc is not None
    if not component.doc.params:
        return ["Takes no props.", ""]
    rows = ["| Prop | Type | Default | Description |", "| --- | --- | --- | --- |"]
    defaults = component.signature.props or {}
    for param in component.doc.params:
        name = param.name[len("props.") :]
        default = defaults.get(name)
        shown = f"`{_cell(default)}`" if default is not None else ("optional" if param.optional else "**required**")
        rows.append(f"| `{name}` | `{_cell(param.type)}` | {shown} | {_cell(param.description)} |")
    lines = [*rows, ""]
    if component.signature.has_rest:
        lines += ["Other props are passed to the root element.", ""]
    return lines


# --------------------------------------------------------------------------
# panels-sdk.md
# --------------------------------------------------------------------------

_SDK_GROUPS = ("Lifecycle", "Context properties", "View state and theme", "Data", "Decisions", "Python", "Services")


def _sdk_api_names(source: str) -> set[str]:
    names = set(re.findall(r"\bapi\.(\w+)\s*=(?!=)", source))
    literal = re.search(r"var api = \{", source)
    if literal is None:
        raise PanelReferenceError("scistudio-panel.js: 'var api = {' not found")
    start = literal.end() - 1
    body = source[start : _matching(source, start, "{", "}")]
    names |= set(re.findall(r"^\s{4}(\w+):\s*function\b", body, re.M))
    return names


def _sdk_signature(source: str, name: str) -> str | None:
    match = re.search(rf"\bapi\.{name}\s*=\s*function\s*\(([^)]*)\)", source) or re.search(
        rf"^\s+{name}:\s*function\s*\(([^)]*)\)", source, re.M
    )
    return f"{name}({match.group(1).strip()})" if match else None


def _provides(kind: str, *, has_python: bool) -> tuple[list[str], list[str]]:
    """What ``PanelContext.provides`` grants a context of ``kind``; it reads only these two fields."""
    stand_in = cast("PanelContext", SimpleNamespace(kind=kind, panel=SimpleNamespace(has_python=has_python)))
    return PanelContext.provides(stand_in)


def _context_table() -> list[str]:
    rows = ["| Context | Operations | Services |", "| --- | --- | --- |"]
    for kind in PANEL_CONTEXTS:
        with_python = _provides(kind, has_python=True)
        without = _provides(kind, has_python=False)
        operations = []
        for op in with_python[0]:
            operations.append(f"`{op}`" if op in without[0] else f"`{op}` (with `panel.py`)")
        services = ", ".join(f"`{s}`" for s in with_python[1])
        rows.append(f"| `{kind}` | {', '.join(operations)} | {services} |")
    return [*rows, ""]


def _libraries() -> list[str]:
    index = json.loads(LIB_INDEX.read_text(encoding="utf-8"))
    rows = ["| Library | Version | Files |", "| --- | --- | --- |"]
    for library in index["libraries"]:
        files = ", ".join(
            f"`{library['name']}@{library['version']}/{f}`"
            for f in library["files"]
            if f.endswith((".js", ".mjs")) and f.split("/")[0] in ("dist", "build")
        )
        rows.append(f"| {library['name']} | `{library['version']}` | {files} |")
    return [*rows, ""]


def render_sdk_page() -> str:
    path = SDK_DIR / "scistudio-panel.js"
    source = path.read_text(encoding="utf-8")
    blocks = parse_blocks(source, where=path.name)

    sample_version = re.search(r'apiVersion:\s*"([^"]+)"', source)
    if sample_version is None or sample_version.group(1) != PANEL_API_VERSION:
        raise PanelReferenceError(
            f"scistudio-panel.js sample mode reports apiVersion {sample_version and sample_version.group(1)!r}, "
            f"the host serves {PANEL_API_VERSION!r}"
        )

    members = {str(b.first("member")): b for b in blocks if "member" in b.tags}
    names = _sdk_api_names(source)
    if set(members) != names:
        raise PanelReferenceError(
            f"scistudio-panel.js: undocumented members {sorted(names - set(members))}, "
            f"documented but absent {sorted(set(members) - names)}"
        )
    out = [
        _BANNER,
        "# Panel SDK: `window.scistudio`\n",
        _stamp(),
        _overview(path) + "\n",
        "## Contexts\n",
        "What `window.scistudio` offers depends on the context. Operations and services "
        "a context does not provide are absent.\n",
        *_context_table(),
    ]
    for group in _SDK_GROUPS:
        in_group = [(n, b) for n, b in members.items() if (b.first("group") or "") == group]
        if not in_group:
            continue
        out.append(f"## {group}\n")
        for name, block in in_group:
            signature = _sdk_signature(source, str(name))
            heading = f"### `scistudio.{signature or name}`"
            out.append(heading + "\n")
            facts = []
            declared = block.first("type")
            if declared:
                split = _split_type(declared)
                if split is None:
                    raise PanelReferenceError(f"scistudio-panel.js {name}: malformed @type {declared!r}")
                facts.append(f"**Type:** `{split[0]}`")
            if block.first("context"):
                contexts = ", ".join(f"`{c.strip()}`" for c in str(block.first("context")).split(","))
                facts.append(f"**Contexts:** {contexts}")
            if facts:
                out.append(" · ".join(facts) + "\n")
            out.append(block.description + "\n")
            if block.params:
                out += ["| Parameter | Type | Description |", "| --- | --- | --- |"]
                for param in block.params:
                    label = f"`{param.name}`" + (" (optional)" if param.optional else "")
                    out.append(f"| {label} | `{_cell(param.type)}` | {_cell(param.description)} |")
                out.append("")
            returns = block.first("returns")
            if returns:
                split = _split_type(returns)
                if split is None:
                    raise PanelReferenceError(f"scistudio-panel.js {name}: malformed @returns {returns!r}")
                tail = f" — {split[1]}" if split[1] else ""
                out.append(f"**Returns:** `{split[0]}`{tail}\n")
    ungrouped = sorted(str(n) for n, b in members.items() if b.first("group") not in _SDK_GROUPS)
    if ungrouped:
        raise PanelReferenceError(f"scistudio-panel.js: members without a known @group: {ungrouped}")

    out += [
        "## Read operations\n",
        "`scistudio.read(op, params)` accepts these operations. A parameter not listed is refused "
        'with `invalid_request`. Every operation also accepts `format`: `"json"` (the default) or '
        '`"binary"` for the array and series reads.\n',
        "| Operation | Target | Parameters | Result |",
        "| --- | --- | --- | --- |",
    ]
    for operation in READ_OPERATIONS.values():
        if operation.params is None:
            params = "_ignored_"
        elif not operation.params:
            params = "none"
        else:
            params = ", ".join(f"`{p}`" for p in operation.params)
        out.append(f"| `{operation.op}` | {operation.target} | {params} | {_cell(operation.result)} |")
    out.append("")

    error_blocks = [b for b in blocks if "errors" in b.tags]
    if len(error_blocks) != 1:
        raise PanelReferenceError("scistudio-panel.js: expected exactly one @errors block")
    documented_errors: dict[str, str] = {}
    for entry in error_blocks[0].tags.get("error", []):
        code, _, description = entry.partition(" ")
        documented_errors[code] = description.strip()
    raised = set(re.findall(r'failure\("(\w+)"', source))
    if raised != set(documented_errors):
        raise PanelReferenceError(
            f"scistudio-panel.js: error codes undocumented {sorted(raised - set(documented_errors))}, "
            f"documented but never raised {sorted(set(documented_errors) - raised)}"
        )
    out += ["## Errors\n", error_blocks[0].description + "\n", "| Code | Meaning |", "| --- | --- |"]
    out += [f"| `{code}` | {_cell(text)} |" for code, text in documented_errors.items()]
    out.append("")

    out += [
        "## Shared libraries\n",
        "Pinned third-party libraries served beside the SDK. Import them by relative path from the "
        "panel page (`../../lib/<name>@<version>/<file>`) or from `scistudio.libBaseUrl`.\n",
        *_libraries(),
        "## Sample mode\n",
        f"Opened outside a SciStudio frame, the SDK answers from `panel.sample.json`; its shape is in "
        f"[the panel descriptor reference]({DESCRIPTOR_PAGE}#panelsamplejson).\n",
    ]
    return "\n".join(out).rstrip() + "\n"


