def _sample_keys_read(source: str) -> set[str]:
    return set(re.findall(r"(?<![\w.])(?:sample|loaded)\.(\w+)", source))


def render_descriptor_page() -> str:
    source = (SDK_DIR / "scistudio-panel.js").read_text(encoding="utf-8")
    samples = [b for b in parse_blocks(source, where="scistudio-panel.js") if "sample" in b.tags]
    if len(samples) != 1:
        raise PanelReferenceError("scistudio-panel.js: expected exactly one @sample block")
    sample = samples[0]
    documented = {p.name for p in sample.params}
    read = _sample_keys_read(source)
    if documented != read:
        raise PanelReferenceError(
            f"panel.sample.json: keys read but undocumented {sorted(read - documented)}, "
            f"documented but never read {sorted(documented - read)}"
        )

    out = [
        _BANNER,
        "# Panel descriptor: `panel.json`\n",
        _stamp(),
        "A panel is a directory holding `panel.json`, an HTML entry page, and optionally "
        "`panel.sample.json` and `panel.py`. `panel.json` declares what the panel is; the host "
        "validates it when panels are discovered and skips a panel whose descriptor is invalid, "
        "reporting why.\n",
        "## Keys\n",
        "| Key | Type | Required | Default | Rule |",
        "| --- | --- | --- | --- | --- |",
    ]
    for entry in DESCRIPTOR_FIELDS:
        required = "yes" if entry.required else "no"
        default = entry.default or "—"
        out.append(f"| `{entry.key}` | {entry.json_type} | {required} | {default} | {_cell(entry.rule)} |")
    out += ["", "## Directory rules\n", *[f"- {rule}" for rule in DESCRIPTOR_FILE_RULES], ""]
    out += ["## Contexts\n"]
    out += [
        "- `preview` — shows a data object in the preview area.",
        "- `interactive` — the window an interactive block opens to collect a decision.",
        "- `miniapp` — a standalone app over one type, optionally backed by `panel.py`.",
        "",
        f"What each context may call is in [the panel SDK reference]({SDK_PAGE}#contexts).\n",
    ]
    if {line.split("`")[1] for line in out if line.startswith("- `") and "—" in line} != set(PANEL_CONTEXTS):
        raise PanelReferenceError("panel-descriptor.md: the context list disagrees with PANEL_CONTEXTS")
    out += [
        "## `panel.sample.json`\n",
        sample.description + "\n",
        "| Key | Type | Description |",
        "| --- | --- | --- |",
    ]
    for param in sample.params:
        label = f"`{param.name}`" + (" (optional)" if param.optional else "")
        out.append(f"| {label} | `{_cell(param.type)}` | {_cell(param.description)} |")
    out.append("")
    return "\n".join(out).rstrip() + "\n"


