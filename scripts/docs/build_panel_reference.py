def _css_tokens() -> list[str]:
    tokens: set[str] = set()
    for sheet in ("panel.css", "renderers.css"):
        tokens |= set(re.findall(r"var\((--ss-[a-z0-9-]+)", (SDK_DIR / sheet).read_text(encoding="utf-8")))
    return sorted(tokens)


def _component_section(component: Component) -> list[str]:
    _check_component(component)
    assert component.doc is not None
    return [f"### `{component.name}`\n", component.doc.description + "\n", *_props_table(component)]


def render_renderers_page() -> str:
    ui_path = SDK_DIR / "panel-ui.js"
    renderers_path = SDK_DIR / "renderers.js"
    ui = _exported_components(ui_path)
    out = [
        _BANNER,
        "# Panel components and stylesheets\n",
        _stamp(),
        "## Stylesheets\n",
        "### `panel.css`\n",
        _overview(SDK_DIR / "panel.css") + "\n",
        "### `renderers.css`\n",
        _overview(SDK_DIR / "renderers.css") + "\n",
        "### Theme tokens\n",
        "The SDK copies the host's `--ss-*` theme tokens onto the panel's root element and sets "
        "`data-theme` to `light` or `dark`. The stylesheets read these tokens, as space-separated "
        "RGB channels, with fallbacks for sample mode.\n",
        *[f"- `{token}`" for token in _css_tokens()],
        "",
        f"## UI components: `sdk/{PANEL_API_MAJOR}/panel-ui.js`\n",
        _overview(ui_path) + "\n",
    ]
    for component in ui.values():
        out += _component_section(component)

    out += [f"## Data views: `sdk/{PANEL_API_MAJOR}/renderers.js`\n", _overview(renderers_path) + "\n"]
    exports = _re_exports(renderers_path)
    if not exports:
        raise PanelReferenceError("renderers.js re-exports nothing")
    cache: dict[str, dict[str, Component]] = {}
    for name, module in exports:
        components = cache.setdefault(module, _exported_components(SDK_DIR / module))
        if name not in components:
            raise PanelReferenceError(f"renderers.js re-exports {name} from {module}, which does not export it")
        component = components[name]
        section = _component_section(component)
        section.insert(1, f"Module: `sdk/{PANEL_API_MAJOR}/{module}`\n")
        out += section
    return "\n".join(out).rstrip() + "\n"


