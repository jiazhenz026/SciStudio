PAGES = {
    SDK_PAGE: ("Panel SDK", "`window.scistudio`: contexts, operations, read operations, errors, libraries"),
    RENDERERS_PAGE: ("Panel components", "stylesheets, UI components, and data views"),
    DESCRIPTOR_PAGE: ("Panel descriptor", "`panel.json` keys and rules, and `panel.sample.json`"),
}

_RENDERERS = {
    SDK_PAGE: render_sdk_page,
    RENDERERS_PAGE: render_renderers_page,
    DESCRIPTOR_PAGE: render_descriptor_page,
}


def render_pages() -> dict[str, str]:
    """Every panel reference page, keyed by file name."""
    return {name: render() for name, render in _RENDERERS.items()}


def index_section() -> list[str]:
    """The API reference index lines that link the panel pages."""
    lines = [
        "## Panel contract\n",
        f"The panel SDK, components, and descriptor (panel API `{PANEL_API_VERSION}`, `{STABILITY}`), "
        "generated from the panel sources.\n",
    ]
    lines += [f"- [{title}]({page}) — {summary}" for page, (title, summary) in PAGES.items()]
    lines.append("")
    return lines


def generate(output_dir: Path = OUTPUT_DIR) -> list[str]:
    """Write the panel reference pages; returns the file names written."""
    output_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in render_pages().items():
        (output_dir / name).write_text(text, encoding="utf-8", newline="\n")
        written.append(name)
        print(f"  [panels] wrote {name}")
    return written


def main() -> int:
    print("Generating the panel API reference ...")
    generate()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
