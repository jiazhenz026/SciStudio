def test_signature_reads_destructured_props_defaults_and_rest() -> None:
    signature = gen.parse_signature('{ class: cls, query = { page: 1, size: "a,b" }, onChange = () => {}, ...rest }')
    assert signature.props == {"class": None, "query": '{ page: 1, size: "a,b" }', "onChange": "() => {}"}
    assert signature.has_rest
    assert gen.parse_signature("props").props is None


def test_param_type_may_contain_braces() -> None:
    (block,) = gen.parse_blocks(
        "/**\n * Text.\n *\n * @param {Array<string | {value, label}>} [props.options] Choices.\n */", where="t"
    )
    (param,) = block.params
    assert (param.name, param.type, param.optional, param.description) == (
        "props.options",
        "Array<string | {value, label}>",
        True,
        "Choices.",
    )
    assert block.description == "Text."


def _write_module(tmp_path: Path, body: str) -> Path:
    path = tmp_path / "module.js"
    path.write_text(body, encoding="utf-8")
    return path


def test_undocumented_export_is_refused(tmp_path: Path) -> None:
    (component,) = gen._exported_components(_write_module(tmp_path, "export function Bare({ a }) {}\n")).values()
    with pytest.raises(gen.PanelReferenceError, match="without a JSDoc"):
        gen._check_component(component)


def test_prop_drift_is_refused(tmp_path: Path) -> None:
    source = "/**\n * Shows a.\n *\n * @param {string} [props.b] Not taken.\n */\nexport function View({ a }) {}\n"
    (component,) = gen._exported_components(_write_module(tmp_path, source)).values()
    with pytest.raises(gen.PanelReferenceError, match=r"undocumented \['a'\].*not taken \['b'\]"):
        gen._check_component(component)


def _sdk_copy(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    sdk = tmp_path / "sdk"
    shutil.copytree(gen.SDK_DIR, sdk)
    monkeypatch.setattr(gen, "SDK_DIR", sdk)
    return sdk / "scistudio-panel.js"


def test_undocumented_sdk_member_is_refused(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    script = _sdk_copy(tmp_path, monkeypatch)
    source = script.read_text(encoding="utf-8")
    script.write_text(source.replace("  window.scistudio = api;", "  api.extra = 1;\n  window.scistudio = api;"))
    with pytest.raises(gen.PanelReferenceError, match=r"undocumented members \['extra'\]"):
        gen.render_sdk_page()


def test_undocumented_sdk_error_code_is_refused(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    script = _sdk_copy(tmp_path, monkeypatch)
    source = script.read_text(encoding="utf-8")
    script.write_text(source.replace('failure("timeout"', 'failure("too_slow"'))
    with pytest.raises(gen.PanelReferenceError, match="too_slow"):
        gen.render_sdk_page()


def test_sample_key_drift_is_refused(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    script = _sdk_copy(tmp_path, monkeypatch)
    source = script.read_text(encoding="utf-8")
    script.write_text(source.replace("viewState: loaded.viewState,", "viewState: loaded.state,"))
    with pytest.raises(gen.PanelReferenceError, match=r"undocumented \['state'\]"):
        gen.render_descriptor_page()


def test_generate_writes_every_page(tmp_path: Path) -> None:
    written = gen.generate(tmp_path)
    assert sorted(written) == sorted(gen.PAGES)
    for name in written:
        assert (tmp_path / name).read_text(encoding="utf-8").endswith("\n")
