"""The generated panel API reference is fresh and refuses to drift from the panel sources."""

from __future__ import annotations

import importlib.util
import re
import shutil
import sys
from pathlib import Path
from types import ModuleType

import pytest

from scistudio.panels.reads import READ_OPERATIONS

ROOT = Path(__file__).resolve().parents[2]
REFERENCE = ROOT / "src" / "scistudio" / "_user_guide" / "api-reference"


def _load_generator() -> ModuleType:
    path = ROOT / "scripts" / "docs" / "build_panel_reference.py"
    spec = importlib.util.spec_from_file_location("build_panel_reference", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules.setdefault("build_panel_reference", module)
    spec.loader.exec_module(module)
    return module


gen = _load_generator()


def test_committed_panel_reference_matches_a_fresh_render() -> None:
    for name, text in gen.render_pages().items():
        committed = (REFERENCE / name).read_text(encoding="utf-8")
        assert committed == text, (
            f"{name} is stale; regenerate with PYTHONPATH=src python scripts/docs/build_panel_reference.py"
        )


def test_reference_index_links_every_panel_page() -> None:
    index = (REFERENCE / "index.md").read_text(encoding="utf-8")
    for line in gen.index_section():
        assert line.strip() in index
    for page in gen.PAGES:
        assert f"]({page})" in index


def test_pages_carry_stability_and_api_version() -> None:
    from scistudio.panels.descriptor import PANEL_API_VERSION

    for text in gen.render_pages().values():
        assert "Stability:** `provisional`" in text
        assert f"Panel API version:** `{PANEL_API_VERSION}`" in text
        assert text.startswith("<!-- GENERATED by scripts/docs/build_panel_reference.py.")


def test_read_operations_match_the_host_bridge_allowlist() -> None:
    bridge = (ROOT / "frontend" / "src" / "panels" / "bridge.ts").read_text(encoding="utf-8")
    block = re.search(r"const READ_OPS = new Set\(\[(.*?)\]\)", bridge, re.S)
    assert block is not None
    assert set(re.findall(r'"([\w.]+)"', block.group(1))) == set(READ_OPERATIONS)


def test_every_descriptor_field_and_read_operation_is_rendered() -> None:
    from scistudio.panels.descriptor import DESCRIPTOR_FIELDS

    pages = gen.render_pages()
    for field in DESCRIPTOR_FIELDS:
        assert f"| `{field.key}` |" in pages[gen.DESCRIPTOR_PAGE]
    for op in READ_OPERATIONS:
        assert f"| `{op}` |" in pages[gen.SDK_PAGE]


