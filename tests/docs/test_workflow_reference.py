def test_a_key_without_a_description_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    class Undocumented(BaseModel):
        """A model with an undocumented key."""

        name: str

    class File(BaseModel):
        """A file."""

        body: Undocumented = Field(description="The body.")

    monkeypatch.setattr(gen, "ROOT_MODEL", File)
    monkeypatch.setattr(gen, "_models_by_name", lambda: {"File": File, "Undocumented": Undocumented})
    with pytest.raises(gen.WorkflowReferenceError, match=r"Undocumented\.name has no description"):
        gen.render_page()


def test_a_model_without_its_own_docstring_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    class Bare(BaseModel):
        name: str = Field(description="A name.")

    monkeypatch.setattr(gen, "ROOT_MODEL", Bare)
    monkeypatch.setattr(gen, "_models_by_name", lambda: {"Bare": Bare})
    with pytest.raises(gen.WorkflowReferenceError, match="has no docstring of its own"):
        gen.render_page()


def test_a_validator_without_a_docstring_is_refused(monkeypatch: pytest.MonkeyPatch) -> None:
    class Checked(BaseModel):
        """A model with an undocumented rule."""

        name: str = Field(description="A name.")

        @field_validator("name")
        @classmethod
        def no_spaces(cls, v: str) -> str:
            return v

    monkeypatch.setattr(gen, "ROOT_MODEL", Checked)
    monkeypatch.setattr(gen, "_models_by_name", lambda: {"Checked": Checked})
    with pytest.raises(gen.WorkflowReferenceError, match="validator no_spaces has no docstring"):
        gen.render_page()
